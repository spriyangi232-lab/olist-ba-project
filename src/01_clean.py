"""
01_clean.py - Load, clean and validate the Olist data, then build a SQLite database.

What this script does, in order:
  1. Loads the 8 CSVs we need (the geolocation file is deliberately skipped).
  2. Checks row counts against the expected Kaggle numbers.
  3. Parses all date columns and translates product categories to English.
  4. Keeps only the LATEST review per order.
  5. Applies the project definitions (analysis population, time window, late flag,
     delay days, journey stages, seller SLA breach, route).
  6. Flags data-quality issues instead of hiding them.
  7. Writes every table into data/processed/olist.db plus two cleaned CSVs.
  8. Writes docs/data_validation_report.md and the data section of results/metrics.json.

Run from the project root:   python src/01_clean.py
"""

import json
import sqlite3
from pathlib import Path

import pandas as pd

# ---------------------------------------------------------------------------
# Paths (everything is relative to the project root, one level above /src)
# ---------------------------------------------------------------------------
ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
PROCESSED = ROOT / "data" / "processed"
DOCS = ROOT / "docs"
RESULTS = ROOT / "results"
DB_PATH = PROCESSED / "olist.db"

PROCESSED.mkdir(parents=True, exist_ok=True)
DOCS.mkdir(exist_ok=True)
RESULTS.mkdir(exist_ok=True)

# Minimum orders a purchase month needs to stay in the analysis window
THIN_MONTH_THRESHOLD = 500

# Row counts published on Kaggle - used to confirm the download is complete
EXPECTED_ROWS = {
    "orders": 99441,
    "order_items": 112650,
    "order_reviews": 99224,
    "customers": 99441,
    "sellers": 3095,
    "products": 32951,
    "order_payments": 103886,
}

# The report is built up as a list of markdown lines and written at the end
report = []


def log(line=""):
    """Print a line to the console AND add it to the validation report."""
    print(line)
    report.append(line)


def pct(part, whole):
    """Percentage rounded to 2 decimals (returns 0 if whole is 0)."""
    return round(100 * part / whole, 2) if whole else 0.0


# ---------------------------------------------------------------------------
# 1. Load the CSVs
# ---------------------------------------------------------------------------
files = {
    "orders": "olist_orders_dataset.csv",
    "order_items": "olist_order_items_dataset.csv",
    "order_reviews": "olist_order_reviews_dataset.csv",
    "customers": "olist_customers_dataset.csv",
    "sellers": "olist_sellers_dataset.csv",
    "products": "olist_products_dataset.csv",
    "order_payments": "olist_order_payments_dataset.csv",
    "category_translation": "product_category_name_translation.csv",
}
df = {name: pd.read_csv(RAW / fname) for name, fname in files.items()}

log("# Data Validation Report")
log()
log("Generated by `src/01_clean.py`. Every number below is computed by the script; "
    "re-running the script regenerates this file.")
log()
log("Source: Brazilian E-Commerce Public Dataset by Olist (Kaggle, CC BY-NC-SA 4.0). "
    "The geolocation file is not used.")
log()

# ---------------------------------------------------------------------------
# 2. Row counts vs expected
# ---------------------------------------------------------------------------
log("## 1. Row counts")
log()
log("| Table | Rows loaded | Expected | Match |")
log("|---|---:|---:|:---:|")
for name, table in df.items():
    expected = EXPECTED_ROWS.get(name)
    match = "-" if expected is None else ("Yes" if len(table) == expected else "**NO**")
    exp_txt = "-" if expected is None else f"{expected:,}"
    log(f"| {name} | {len(table):,} | {exp_txt} | {match} |")
log()

# ---------------------------------------------------------------------------
# 3. Nulls and duplicate keys in the raw tables
# ---------------------------------------------------------------------------
log("## 2. Missing values in raw tables (columns with at least one null)")
log()
log("| Table | Column | Nulls | % of rows |")
log("|---|---|---:|---:|")
for name, table in df.items():
    nulls = table.isna().sum()
    for col, n in nulls[nulls > 0].items():
        log(f"| {name} | {col} | {n:,} | {pct(n, len(table))}% |")
log()

log("## 3. Duplicate checks")
log()
dup_checks = [
    ("orders", ["order_id"]),
    ("customers", ["customer_id"]),
    ("sellers", ["seller_id"]),
    ("products", ["product_id"]),
    ("order_items", ["order_id", "order_item_id"]),
    ("order_reviews", ["review_id"]),
    ("order_reviews", ["order_id"]),
]
log("| Table | Key | Duplicate rows |")
log("|---|---|---:|")
for name, key in dup_checks:
    n_dup = df[name].duplicated(subset=key).sum()
    log(f"| {name} | {', '.join(key)} | {n_dup:,} |")
log()
log("Duplicate `order_id` in reviews means some orders have more than one review. "
    "Duplicate `review_id` means the same review text was attached to several orders. "
    "Both are handled in section 5.")
log()

# ---------------------------------------------------------------------------
# 4. Parse dates and translate categories
# ---------------------------------------------------------------------------
order_date_cols = [
    "order_purchase_timestamp",
    "order_approved_at",
    "order_delivered_carrier_date",
    "order_delivered_customer_date",
    "order_estimated_delivery_date",
]
orders = df["orders"].copy()
for col in order_date_cols:
    orders[col] = pd.to_datetime(orders[col])

items = df["order_items"].copy()
items["shipping_limit_date"] = pd.to_datetime(items["shipping_limit_date"])

reviews = df["order_reviews"].copy()
reviews["review_creation_date"] = pd.to_datetime(reviews["review_creation_date"])
reviews["review_answer_timestamp"] = pd.to_datetime(reviews["review_answer_timestamp"])

# Category translation: two Portuguese names are missing from the translation file,
# so we add them by hand. Products with no category at all become 'unknown'.
translation = dict(zip(df["category_translation"]["product_category_name"],
                       df["category_translation"]["product_category_name_english"]))
products = df["products"].copy()
untranslated = sorted(set(products["product_category_name"].dropna()) - set(translation))
manual_translation = {
    "pc_gamer": "pc_gamer",
    "portateis_cozinha_e_preparadores_de_alimentos": "kitchen_portables_and_food_preparers",
}
translation.update(manual_translation)
products["product_category"] = products["product_category_name"].map(translation).fillna("unknown")

log("## 4. Category translation")
log()
log(f"- Portuguese categories missing from the translation file: {len(untranslated)} "
    f"({', '.join(untranslated)}). Translated manually in the script.")
n_no_cat = products["product_category_name"].isna().sum()
log(f"- Products with no category: {n_no_cat:,} ({pct(n_no_cat, len(products))}%). Labelled `unknown`.")
log()

# ---------------------------------------------------------------------------
# 5. Reviews: keep the latest review per order
# ---------------------------------------------------------------------------
# Sort so the most recent answer comes last, then keep the last row per order.
reviews_sorted = reviews.sort_values(["order_id", "review_answer_timestamp", "review_creation_date"])
reviews_latest = reviews_sorted.drop_duplicates(subset="order_id", keep="last")
n_multi_review_orders = (reviews.groupby("order_id").size() > 1).sum()

log("## 5. Reviews")
log()
log(f"- Review rows: {len(reviews):,}; distinct orders with a review: {reviews['order_id'].nunique():,}.")
log(f"- Orders with more than one review: {n_multi_review_orders:,}. "
    f"Rule: keep the latest review by `review_answer_timestamp` -> {len(reviews_latest):,} reviews kept.")
log("- Bad review = score 1-2. Good review = score 4-5. Score 3 is neutral.")
log()

# ---------------------------------------------------------------------------
# 6. Analysis population and time window
# ---------------------------------------------------------------------------
log("## 6. Analysis population and time window")
log()
log("**Definition:** orders with `order_status = 'delivered'` and a non-null "
    "`order_delivered_customer_date`, purchased in a month with at least "
    f"{THIN_MONTH_THRESHOLD} orders.")
log()

orders["purchase_month"] = orders["order_purchase_timestamp"].dt.strftime("%Y-%m")

# Monthly order counts (all statuses) decide which months are "thin"
monthly = orders.groupby("purchase_month").size().rename("orders").reset_index()
monthly["kept"] = monthly["orders"] >= THIN_MONTH_THRESHOLD
kept_months = monthly.loc[monthly["kept"], "purchase_month"].tolist()

log("Orders per purchase month (all statuses):")
log()
log("| Month | Orders | Kept |")
log("|---|---:|:---:|")
for _, row in monthly.iterrows():
    log(f"| {row['purchase_month']} | {row['orders']:,} | {'Yes' if row['kept'] else 'No'} |")
log()
log(f"Window kept: **{kept_months[0]} to {kept_months[-1]}** ({len(kept_months)} months).")
log()

# Step-by-step funnel so the reader can see exactly what was removed and why
total_orders = len(orders)
is_delivered = orders["order_status"] == "delivered"
has_delivery_date = orders["order_delivered_customer_date"].notna()
in_window = orders["purchase_month"].isin(kept_months)

n_not_delivered = (~is_delivered).sum()
n_delivered_no_date = (is_delivered & ~has_delivery_date).sum()
n_outside_window = (is_delivered & has_delivery_date & ~in_window).sum()
population = orders[is_delivered & has_delivery_date & in_window].copy()

log("Exclusion funnel:")
log()
log("| Step | Orders removed | Orders remaining |")
log("|---|---:|---:|")
log(f"| All orders | - | {total_orders:,} |")
remaining = total_orders - n_not_delivered
log(f"| Status is not 'delivered' | {n_not_delivered:,} | {remaining:,} |")
remaining -= n_delivered_no_date
log(f"| Delivered but no customer delivery date | {n_delivered_no_date:,} | {remaining:,} |")
remaining -= n_outside_window
log(f"| Purchased in a thin month (outside window) | {n_outside_window:,} | {remaining:,} |")
log()
log(f"**Analysis population: {len(population):,} orders.**")
log()

# ---------------------------------------------------------------------------
# 7. Late flag, delay days, journey stages
# ---------------------------------------------------------------------------
# The estimated date has no time part, so we compare calendar dates only.
delivered_date = population["order_delivered_customer_date"].dt.normalize()
estimated_date = population["order_estimated_delivery_date"].dt.normalize()

population["delay_days"] = (delivered_date - estimated_date).dt.days   # positive = late
population["is_late"] = (population["delay_days"] > 0).astype(int)

# Helper: difference between two timestamps in days (with decimals)
def days_between(later, earlier):
    return (later - earlier).dt.total_seconds() / 86400

population["approval_days"] = days_between(population["order_approved_at"],
                                           population["order_purchase_timestamp"])
population["seller_handling_days"] = days_between(population["order_delivered_carrier_date"],
                                                  population["order_approved_at"])
population["carrier_transit_days"] = days_between(population["order_delivered_customer_date"],
                                                  population["order_delivered_carrier_date"])
population["promised_lead_days"] = days_between(population["order_estimated_delivery_date"],
                                                population["order_purchase_timestamp"])
population["actual_lead_days"] = days_between(population["order_delivered_customer_date"],
                                              population["order_purchase_timestamp"])

# Late-delay bucket (only meaningful for late orders)
bins = [0, 3, 7, 14, float("inf")]
labels = ["1-3 days", "4-7 days", "8-14 days", "15+ days"]
population["delay_bucket"] = pd.cut(population["delay_days"], bins=bins, labels=labels, right=True)
# Orders with delay_days <= 0 fall outside the bins (NaN) - these are the on-time orders
population["delay_bucket"] = population["delay_bucket"].astype(object).fillna("on time")

# ---------------------------------------------------------------------------
# 8. Data-quality flags on the journey stages
# ---------------------------------------------------------------------------
dq = pd.DataFrame(index=population.index)
dq["missing_approved_at"] = population["order_approved_at"].isna()
dq["missing_carrier_date"] = population["order_delivered_carrier_date"].isna()
dq["negative_approval"] = population["approval_days"] < 0
dq["negative_seller_handling"] = population["seller_handling_days"] < 0
dq["negative_carrier_transit"] = population["carrier_transit_days"] < 0
dq["carrier_before_purchase"] = (population["order_delivered_carrier_date"]
                                 < population["order_purchase_timestamp"])
dq["delivered_before_purchase"] = (population["order_delivered_customer_date"]
                                   < population["order_purchase_timestamp"])

# An order is usable for stage analysis only if no flag is raised
population["stage_valid"] = (~dq.any(axis=1)).astype(int)
n_stage_invalid = (population["stage_valid"] == 0).sum()

log("## 7. Journey-stage data quality")
log()
log("Stage definitions: approval = approved - purchase; seller handling = carrier handover - approved; "
    "carrier transit = delivered - carrier handover; promised lead time = estimated - purchase.")
log()
log("| Issue | Orders | % of population |")
log("|---|---:|---:|")
for col in dq.columns:
    n = dq[col].sum()
    log(f"| {col.replace('_', ' ')} | {n:,} | {pct(n, len(population))}% |")
log(f"| **Any issue (excluded from stage analysis)** | **{n_stage_invalid:,}** | "
    f"**{pct(n_stage_invalid, len(population))}%** |")
log()
log("These orders stay in the late-rate and review analysis (their delivered and estimated dates are fine). "
    "They are only excluded when stage durations are compared, using the `stage_valid` column.")
log()

# ---------------------------------------------------------------------------
# 9. Attach customer, review and item details to each order
# ---------------------------------------------------------------------------
customers = df["customers"]
population = population.merge(
    customers[["customer_id", "customer_unique_id", "customer_state", "customer_city"]],
    on="customer_id", how="left")

population = population.merge(
    reviews_latest[["order_id", "review_score", "review_answer_timestamp"]],
    on="order_id", how="left")
population["has_review"] = population["review_score"].notna().astype(int)
population["is_bad_review"] = population["review_score"].isin([1, 2]).astype(int)
population["is_good_review"] = population["review_score"].isin([4, 5]).astype(int)

# Item-level summary per order: number of items, sellers, value, freight
items = items.merge(products[["product_id", "product_category"]], on="product_id", how="left")
items["product_category"] = items["product_category"].fillna("unknown")
order_summary = items.groupby("order_id").agg(
    n_items=("order_item_id", "count"),
    n_sellers=("seller_id", "nunique"),
    order_value=("price", "sum"),
    freight_value=("freight_value", "sum"),
).reset_index()

# Main category of an order = category of its most expensive item
main_cat = (items.sort_values(["order_id", "price"], ascending=[True, False])
                 .drop_duplicates("order_id")[["order_id", "product_category"]]
                 .rename(columns={"product_category": "main_category"}))

population = population.merge(order_summary, on="order_id", how="left")
population = population.merge(main_cat, on="order_id", how="left")
population["is_multi_seller"] = (population["n_sellers"] > 1).astype(int)

n_no_items = population["n_items"].isna().sum()
n_no_review = (population["has_review"] == 0).sum()

# ---------------------------------------------------------------------------
# 10. Order-seller table (one row per order_id + seller_id pair)
# ---------------------------------------------------------------------------
# If a seller has several items in one order they share the same handover,
# so we take the latest shipping limit for that pair.
pairs = items.groupby(["order_id", "seller_id"]).agg(
    shipping_limit_date=("shipping_limit_date", "max"),
    n_items=("order_item_id", "count"),
    item_value=("price", "sum"),
).reset_index()
pairs = pairs.merge(df["sellers"][["seller_id", "seller_state", "seller_city"]], on="seller_id", how="left")

order_cols = ["order_id", "purchase_month", "customer_state", "order_delivered_carrier_date",
              "is_late", "delay_days", "seller_handling_days", "stage_valid",
              "review_score", "is_bad_review", "is_multi_seller"]
order_sellers = pairs.merge(population[order_cols], on="order_id", how="inner")

# Seller SLA breach: handed to carrier after the shipping limit date.
# Left as NULL when the carrier date is missing.
order_sellers["sla_breach"] = (order_sellers["order_delivered_carrier_date"]
                               > order_sellers["shipping_limit_date"]).astype("Int64")
order_sellers.loc[order_sellers["order_delivered_carrier_date"].isna(), "sla_breach"] = pd.NA
order_sellers["route"] = order_sellers["seller_state"] + " -> " + order_sellers["customer_state"]

# For single-seller orders we can also put the route on the order itself
single_route = (order_sellers[order_sellers["is_multi_seller"] == 0][["order_id", "seller_id", "seller_state", "route"]])
population = population.merge(single_route, on="order_id", how="left")

log("## 8. Joins and seller-level table")
log()
log(f"- Population orders with no matching items: {n_no_items:,}.")
log(f"- Population orders with no review: {n_no_review:,} ({pct(n_no_review, len(population))}%). "
    "They are kept for late-rate analysis and left out of review averages.")
n_multi = population["is_multi_seller"].sum()
log(f"- Multi-seller orders: {n_multi:,} ({pct(n_multi, len(population))}% of the population). "
    "Seller-level analysis uses (order_id, seller_id) pairs; the order-level `route` column is "
    "filled only for single-seller orders.")
log(f"- Order-seller pairs: {len(order_sellers):,}.")
n_sla_null = order_sellers["sla_breach"].isna().sum()
log(f"- Pairs with no carrier date (SLA breach not computable): {n_sla_null:,}.")
log()

# ---------------------------------------------------------------------------
# 11. Sanity checks against the numbers already known for this dataset
# ---------------------------------------------------------------------------
late_rate = population["is_late"].mean()
reviewed = population[population["has_review"] == 1]
avg_score_late = reviewed.loc[reviewed["is_late"] == 1, "review_score"].mean()
avg_score_ontime = reviewed.loc[reviewed["is_late"] == 0, "review_score"].mean()
bad_share_late = reviewed.loc[reviewed["is_late"] == 1, "is_bad_review"].mean()
bad_share_ontime = reviewed.loc[reviewed["is_late"] == 0, "is_bad_review"].mean()

# Same late rate on ALL delivered orders (no window) for comparison
all_delivered = orders[is_delivered & has_delivery_date]
late_rate_all = ((all_delivered["order_delivered_customer_date"].dt.normalize()
                  > all_delivered["order_estimated_delivery_date"].dt.normalize()).mean())

log("## 9. Sanity checks")
log()
log("| Check | Expected (approx.) | This run |")
log("|---|---:|---:|")
log(f"| Late rate, analysis population | 6.8% | {late_rate:.2%} |")
log(f"| Late rate, all delivered orders (no window) | - | {late_rate_all:.2%} |")
log(f"| Avg review score, late orders | 2.3 | {avg_score_late:.2f} |")
log(f"| Avg review score, on-time orders | 4.3 | {avg_score_ontime:.2f} |")
log(f"| Bad-review (1-2) share, late orders | 61% | {bad_share_late:.1%} |")
log(f"| Bad-review (1-2) share, on-time orders | 9% | {bad_share_ontime:.1%} |")
log()

# ---------------------------------------------------------------------------
# 12. Write to SQLite and CSV
# ---------------------------------------------------------------------------
def to_sql_ready(frame):
    """Convert datetime columns to 'YYYY-MM-DD HH:MM:SS' text so SQLite date functions work."""
    out = frame.copy()
    for col in out.columns:
        if pd.api.types.is_datetime64_any_dtype(out[col]):
            out[col] = out[col].dt.strftime("%Y-%m-%d %H:%M:%S")
    return out

tables_to_save = {
    "orders": orders,
    "order_items": items,
    "order_payments": df["order_payments"],
    "order_reviews": reviews,
    "reviews_latest": reviews_latest,
    "customers": customers,
    "sellers": df["sellers"],
    "products": products,
    "category_translation": df["category_translation"],
    "monthly_order_counts": monthly,
    "analysis_orders": population,
    "analysis_order_sellers": order_sellers,
}

if DB_PATH.exists():
    DB_PATH.unlink()  # rebuild from scratch every run
with sqlite3.connect(DB_PATH) as conn:
    for name, table in tables_to_save.items():
        to_sql_ready(table).to_sql(name, conn, index=False)
    # Indexes make the joins in sql/analysis.sql fast
    conn.execute("CREATE INDEX idx_ao_order ON analysis_orders(order_id)")
    conn.execute("CREATE INDEX idx_aos_order ON analysis_order_sellers(order_id)")
    conn.execute("CREATE INDEX idx_aos_seller ON analysis_order_sellers(seller_id)")

to_sql_ready(population).to_csv(PROCESSED / "analysis_orders.csv", index=False)
to_sql_ready(order_sellers).to_csv(PROCESSED / "analysis_order_sellers.csv", index=False)

log("## 10. Outputs")
log()
log(f"- `data/processed/olist.db` with tables: {', '.join(tables_to_save)}.")
log("- `data/processed/analysis_orders.csv` (one row per order in the analysis population).")
log("- `data/processed/analysis_order_sellers.csv` (one row per order-seller pair).")
log()

(DOCS / "data_validation_report.md").write_text("\n".join(report) + "\n", encoding="utf-8")

# ---------------------------------------------------------------------------
# 13. Save data numbers to results/metrics.json (other scripts add their own sections)
# ---------------------------------------------------------------------------
metrics_path = RESULTS / "metrics.json"
metrics = json.loads(metrics_path.read_text(encoding="utf-8")) if metrics_path.exists() else {}
metrics["data"] = {
    "total_orders": int(total_orders),
    "window_start": kept_months[0],
    "window_end": kept_months[-1],
    "window_months": len(kept_months),
    "excluded_not_delivered": int(n_not_delivered),
    "excluded_delivered_no_date": int(n_delivered_no_date),
    "excluded_outside_window": int(n_outside_window),
    "orders_after_status_filter": int(total_orders - n_not_delivered),
    "orders_after_date_filter": int(total_orders - n_not_delivered - n_delivered_no_date),
    "analysis_orders": int(len(population)),
    "stage_invalid_orders": int(n_stage_invalid),
    "stage_invalid_pct": pct(n_stage_invalid, len(population)),
    "carrier_before_approval_orders": int(dq["negative_seller_handling"].sum()),
    "orders_without_review": int(n_no_review),
    "multi_review_orders": int(n_multi_review_orders),
    "multi_seller_orders": int(n_multi),
    "multi_seller_pct": pct(n_multi, len(population)),
    "order_seller_pairs": int(len(order_sellers)),
    "sanity_late_rate_pct": round(100 * late_rate, 2),
    "sanity_avg_score_late": round(avg_score_late, 2),
    "sanity_avg_score_ontime": round(avg_score_ontime, 2),
    "sanity_bad_share_late_pct": round(100 * bad_share_late, 1),
    "sanity_bad_share_ontime_pct": round(100 * bad_share_ontime, 1),
}
metrics_path.write_text(json.dumps(metrics, indent=2), encoding="utf-8")

print("\nDone. Report saved to docs/data_validation_report.md")
